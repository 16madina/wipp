// Builds src/generated/tr-en.ts from the list of French texts (i18n-fr-list.json) and the English
// lines in scripts/i18n-en/*.txt (« index|English », ⏎ = line break). Usage: node scripts/i18n-apply-en.mjs
import fs from "node:fs";
const fr = JSON.parse(fs.readFileSync("scripts/i18n-fr-list.json", "utf8"));
const en = {};
let missing = 0;
const seen = new Set();
for (const file of fs.readdirSync("scripts/i18n-en").filter((f) => f.endsWith(".txt")).sort()) {
  for (const line of fs.readFileSync(`scripts/i18n-en/${file}`, "utf8").split("\n")) {
    const cut = line.indexOf("|");
    if (cut < 1) continue;
    const i = Number(line.slice(0, cut));
    if (!Number.isInteger(i) || fr[i] === undefined) { console.log("ligne inconnue", file, line.slice(0, 40)); continue; }
    seen.add(i);
    const text = line.slice(cut + 1).replaceAll("⏎", "\n");
    // Same number of {0} places on both sides, or the app would show a hole.
    const a = (fr[i].match(/\{\d+\}/g) ?? []).sort().join(), b = (text.match(/\{\d+\}/g) ?? []).sort().join();
    if (a !== b) console.log(`places différentes [${i}] ${fr[i].slice(0, 50)} → ${text.slice(0, 50)}`);
    if (text !== fr[i]) en[fr[i]] = text;
  }
}
for (let i = 0; i < fr.length; i++) if (!seen.has(i)) missing++;
const body = Object.entries(en).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
fs.writeFileSync("src/generated/tr-en.ts", `/* Generated by scripts/i18n-apply-en.mjs from scripts/i18n-en/*.txt. Do not edit. */\nexport const TR_EN: Record<string, string> = {\n${body}\n};\n`);
console.log(`${Object.keys(en).length} traductions écrites, ${missing} textes sans ligne anglaise`);
