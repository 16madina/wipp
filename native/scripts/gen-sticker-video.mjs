// Lists the sticker clips bundled in the app (assets/wipp/stickers/**/*.mp4|webm) in src/generated/video.ts.
// Usage (from native/): node scripts/gen-sticker-video.mjs
import fs from "node:fs";
import path from "node:path";
const root = "assets/wipp";
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(mp4|webm)$/.test(e.name)) files.push(path.relative(root, p).replaceAll("\\", "/"));
  }
})(path.join(root, "stickers"));
files.sort();
const body = files.map((f) => `  '${f}': require("../../assets/wipp/${f}"),`).join("\n");
fs.writeFileSync("src/generated/video.ts", `/* eslint-disable @typescript-eslint/no-require-imports */\n/* Generated by scripts/gen-sticker-video.mjs from assets/wipp/stickers video. Do not edit. */\nexport const stickerVideo = {\n${body}\n} as const;\n`);
console.log(files.length, "clips");
