#!/usr/bin/env node
// Measures the real length of every surprise animation (WebP) and writes src/generated/anim-durations.ts.
// Run from native/ after adding or replacing an animation: node scripts/gen-anim-durations.mjs
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const dir = path.resolve("../public/wipp-media/fx/surprise/anims");
const out = {};
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".webp")).sort()) {
  const info = execFileSync("webpmux", ["-info", path.join(dir, file)], { encoding: "utf8" });
  let ms = 0;
  for (const line of info.split("\n")) if (/^\s*\d+:/.test(line)) ms += Number(line.trim().split(/\s+/)[6]) || 0;
  out[file.slice(0, -5)] = ms;
}
const body =
  "/** Real length of each surprise animation (ms), measured from the WebP files. Generated by scripts/gen-anim-durations.mjs. */\n" +
  "export const ANIM_MS: Record<string, number> = {\n" +
  Object.entries(out).map(([k, v]) => `  "${k}": ${v},\n`).join("") +
  "};\n";
fs.writeFileSync("src/generated/anim-durations.ts", body);
console.log(`animations: ${Object.keys(out).length}`);
