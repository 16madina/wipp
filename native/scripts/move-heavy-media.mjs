// Moves heavy animated stickers/effects out of the app bundle into the website
// (wippapp.com/wipp-media/...). Posters (first frame) stay in the app for instant display.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve("assets/wipp");
const site = path.resolve("../public/wipp-media");
const LIMIT = 400 * 1024;
const moved = [];

function walk(dir) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(p);
    else {
      const rel = path.relative(root, p).replaceAll("\\", "/");
      const heavy = fs.statSync(p).size > LIMIT;
      if (heavy && /^(stickers|fx)\//.test(rel) && !/-poster\.|\.mp4$/.test(rel) && /\.(webp|gif|png|jpg)$/i.test(rel)) {
        const dest = path.join(site, rel);
        fs.mkdirSync(path.dirname(dest), { recursive: true });
        fs.renameSync(p, dest);
        moved.push(rel);
      }
    }
  }
}

walk(root);
const listFile = "src/generated/remote-media.ts";
const prev = fs.existsSync(listFile) ? JSON.parse(fs.readFileSync(listFile, "utf8").match(/\[[\s\S]*\]/)[0]) : [];
const all = [...new Set([...prev, ...moved])].sort();
fs.writeFileSync(listFile, `/* Generated by scripts/move-heavy-media.mjs. Do not edit. */\nexport const remoteMedia: string[] = ${JSON.stringify(all, null, 2)};\n`);
console.log(`moved ${moved.length} files`);
