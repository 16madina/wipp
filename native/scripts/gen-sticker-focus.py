# Where the character sits in the first image of each animated Wippmoji (the canvas also holds room for the
# animation: tears, rising hearts…). The app zooms the still picture on it so every emoji looks the same size.
# Needs Pillow:  python3 -m venv /tmp/v && /tmp/v/bin/pip install pillow && /tmp/v/bin/python scripts/gen-sticker-focus.py
import glob, json, os
from PIL import Image

SRCS = ["../public/wipp-media/stickers/moji-v", "assets/wipp/stickers/moji-v"]  # heavy ones are served by the site, light ones ship in the app
rows = {}
for f in sorted(g for s in SRCS for g in glob.glob(f"{s}/moji-*.webp")):
    im = Image.open(f)
    W, H = im.size
    im.seek(0)
    bb = im.convert("RGBA").getchannel("A").point(lambda a: 255 if a > 40 else 0).getbbox()
    if not bb:
        continue
    r = lambda v: round(v, 3)
    rows[os.path.basename(f)[:-5]] = [r(W / H), r(bb[0] / W), r(bb[1] / H), r(bb[2] / W), r(bb[3] / H)]
body = "\n".join(f"  {json.dumps(k)}: {json.dumps(v)}," for k, v in rows.items())
open("src/generated/sticker-focus.ts", "w").write(
    "/* Generated by scripts/gen-sticker-focus.py. Do not edit. [width/height, left, top, right, bottom] of the character, as parts of the picture. */\n"
    f"export const STICKER_FOCUS: Record<string, [number, number, number, number, number]> = {{\n{body}\n}};\n"
)
print(len(rows), "stickers")
