export const EMOJI_PREFIX = "e:";

export function isEmojiSticker(id: string | undefined): boolean {
  return Boolean(id?.startsWith(EMOJI_PREFIX) && id.length > EMOJI_PREFIX.length);
}

export function emojiFromStickerId(id: string) {
  return isEmojiSticker(id) ? id.slice(EMOJI_PREFIX.length) : "";
}

export function stickerIdFromEmoji(emoji: string) {
  return `${EMOJI_PREFIX}${emoji}`;
}

